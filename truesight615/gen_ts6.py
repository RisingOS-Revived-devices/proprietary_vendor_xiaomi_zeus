# Regenerates ts6_names.h and ts6_tramp.S from ts6_symbols.txt, the GL/EGL
# symbols libTrueSight imports. Rerun after updating libTrueSight.

import os

HERE = os.path.dirname(os.path.abspath(__file__))
# Implemented in ts6_shim.c instead of forwarded to the driver.
LOCAL = {'eglGetNativeClientBufferANDROID'}

with open(os.path.join(HERE, 'ts6_symbols.txt')) as f:
    names = sorted(line.strip() for line in f if line.strip())
forwarded = [n for n in names if n not in LOCAL]

HEADER = '// Generated by gen_ts6.py from ts6_symbols.txt. Do not edit.\n'

# BTI/PAC-compatible object, required by the platform's -z bti-report=error
BTI_NOTE = '''.pushsection .note.gnu.property, "a"
.balign 8
.long 4
.long 16
.long 5
.asciz "GNU"
.long 0xc0000000
.long 4
.long 3
.long 0
.popsection
'''

with open(os.path.join(HERE, 'ts6_names.h'), 'w') as f:
    f.write(HEADER)
    f.write(f'#define TS6_COUNT {len(forwarded)}\n')
    f.write('static const char *const ts6_names[TS6_COUNT] = {\n')
    f.writelines(f'    "{n}",\n' for n in forwarded)
    f.write('};\n')

with open(os.path.join(HERE, 'ts6_tramp.S'), 'w') as f:
    f.write(HEADER)
    f.write('// ts6_<name> jumps through ts6_ptrs[i]; an empty slot loads the driver first.\n')
    f.write('.text\n')
    for i, n in enumerate(forwarded):
        f.write(
            f'.globl ts6_{n}\n'
            f'.type ts6_{n},%function\n'
            f'ts6_{n}:\n'
            f'    bti c\n'
            f'    adrp x16, ts6_ptrs+{8 * i}\n'
            f'    ldr x16, [x16, #:lo12:ts6_ptrs+{8 * i}]\n'
            f'    cbz x16, 1f\n'
            f'    br x16\n'
            f'1:  mov x17, #{i}\n'
            f'    b ts6_slow\n'
            f'.size ts6_{n}, .-ts6_{n}\n'
        )
    f.write(BTI_NOTE)

with open(os.path.join(HERE, 'ts6_rename.map'), 'w') as f:
    f.writelines(f'{n} ts6_{n}\n' for n in names)
